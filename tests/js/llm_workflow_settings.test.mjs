import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

test('workflow saves a second key for the same provider and its model', async () => {
  const source = readFileSync(new URL('../../pages/js/app.js', import.meta.url), 'utf8');
  const elements = new Map();
  const element = selector => {
    if (!elements.has(selector)) elements.set(selector, {
      value: '', innerHTML: '', querySelector: element, querySelectorAll: () => [],
      insertAdjacentHTML() {},
    });
    return elements.get(selector);
  };
  const credentials = [
    { credential_id: 'first', provider: 'openai', status: 'active', model: 'gpt-4o' },
    { credential_id: 'second', provider: 'openai', status: 'active', model: 'gpt-4o-mini' },
  ];
  let saved;
  const context = vm.createContext({
    window: { escapeHtml: String },
    document: { getElementById: element },
    apiRequest: async (path, options) => {
      if (options) { saved = options.body; return saved; }
      return path.endsWith('llm-credentials') ? credentials : {
        mode: 'byok', provider: 'openai', default_credential_id: 'first',
      };
    },
  });
  const start = source.indexOf('const OPENHIRE_LLM_PROVIDERS');
  const end = source.indexOf('/** GET /admin/users', start);
  vm.runInContext(source.slice(start, end), context);
  const workflow = await context.mountLlmWorkflowSettings('test');
  // The browser selects the provider option generated by openModal().
  element('[data-provider]').value = 'openai';
  element('#testChange').onclick();
  element('[data-key]').value = 'second';
  element('[data-key]').onchange();
  assert.equal(element('[data-key]').value, 'second');
  assert.equal(element('[data-model]').value, 'gpt-4o-mini');
  element('[data-apply]').onclick();
  await workflow.save();
  assert.equal(saved.default_credential_id, 'second');
  assert.equal(saved.model, 'gpt-4o-mini');
});
